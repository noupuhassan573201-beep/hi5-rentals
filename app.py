@app.post("/bookings")
def book():
    data = request.get_json(silent=True)
    if not isinstance(data, dict):
        return jsonify(error="Invalid request."), 400
    if data.get("token") != session.get("csrf") or not session.get("csrf"):
        return jsonify(error="Refresh the page and try again."), 403
    name, phone = data.get("name"), data.get("phone")
    if not isinstance(name, str) or not 1 <= len(name.strip()) <= 100 or not isinstance(phone, str) or not re.fullmatch(r"[0-9]{10}", phone):
        return jsonify(error="Enter your name and a 10-digit mobile number."), 400
    try:
        pickup, end = date.fromisoformat(data["pickup"]), date.fromisoformat(data["returnDate"])
        vehicle_id = int(data["vehicle"])
    except (KeyError, TypeError, ValueError, OverflowError):
        return jsonify(error="Select a vehicle and enter valid dates."), 400
    if pickup < datetime.now(ZoneInfo("Asia/Kolkata")).date() or end < pickup:
        return jsonify(error="Choose a valid pickup and return date."), 400
    connection = db()
    with connection.transaction():
        vehicle = connection.execute("SELECT name,price FROM vehicles WHERE id=%s FOR SHARE", (vehicle_id,)).fetchone()
        if vehicle is None:
            return jsonify(error="This vehicle is no longer listed. Refresh to view the fleet."), 404
        if data.get("price") != vehicle["price"]:
            return jsonify(error="The daily price changed. Refresh to view the latest price."), 409
        reference = "HI5-" + secrets.token_hex(6).upper()
        amount = vehicle["price"] * max(1, (end - pickup).days)
        connection.execute(
            "INSERT INTO bookings (reference,vehicle,customer,phone,pickup,return_date,amount) VALUES (%s,%s,%s,%s,%s,%s,%s)",
            (reference, vehicle["name"], name.strip(), phone, pickup, end, amount),
        )
    return jsonify(reference=reference), 201


@app.route("/admin/login", methods=["GET", "POST"])
def login():
    error = None
    if request.method == "POST":
        require_token(request.form.get("token"))
        forwarded = request.access_route if app.config["SESSION_COOKIE_SECURE"] else []
        address = forwarded[-1] if forwarded else request.remote_addr
        now = monotonic()
        with login_lock:
            started, attempts = login_attempts.get(address, (now, 0))
            if now - started >= 300:
                started, attempts = now, 0
            if attempts >= 10:
                return render_template("admin.html", token=token(), logged_in=False,
                                       error="Too many attempts. Try again in a few minutes."), 429
            login_attempts[address] = (started, attempts + 1)
            login_attempts.move_to_end(address)
            if len(login_attempts) > 4096:
                login_attempts.popitem(last=False)
        password = request.form.get("password", "")
        if len(password) <= 256 and check_password_hash(PASSWORD_HASH, password):
            session.clear()
            session["admin"] = True
            return redirect(url_for("admin"))
        error = "Incorrect password."
    return render_template("admin.html", token=token(), error=error, logged_in=False)


