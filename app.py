def admin_page(error=None, vehicle_id=None, status=200):
    vehicles = fleet()
    selected = next((vehicle for vehicle in vehicles if vehicle["id"] == vehicle_id), None)
    if vehicle_id is not None and selected is None:
        abort(404)
    bookings = db().execute("SELECT * FROM bookings ORDER BY created DESC, reference DESC").fetchall()
    return render_template(
        "admin.html", token=token(), logged_in=True, vehicles=vehicles, selected=selected,
        bookings=bookings, error=error,
    ), status


