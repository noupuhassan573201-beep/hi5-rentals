def token():
    return session.setdefault("csrf", secrets.token_urlsafe(32))


def require_token(value):
    if not isinstance(value, str) or not secrets.compare_digest(value, session.get("csrf", "")) or not value:
        abort(403)


def admin_only(view):
    @wraps(view)
    def wrapped(*args, **kwargs):
        if not session.get("admin"):
            return redirect(url_for("login"))
        return view(*args, **kwargs)
    return wrapped


def fleet():
    rows = db().execute("SELECT id,name,type,price,meta,img,photo IS NOT NULL AS uploaded FROM vehicles ORDER BY id")
    return [dict(row, img=url_for("photo", vehicle_id=row["id"]) if row["uploaded"] else row["img"]) for row in rows]


