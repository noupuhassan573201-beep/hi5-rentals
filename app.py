@app.post("/admin/vehicles")
@app.post("/admin/vehicles/<int:vehicle_id>")
@admin_only
def save_vehicle(vehicle_id=None):
    require_token(request.form.get("token"))
    name = request.form.get("name", "").strip()
    category = request.form.get("type")
    meta = request.form.get("meta", "").strip()
    price = request.form.get("price", type=int)
    if not (0 < len(name) <= 100 and len(meta) <= 200 and category in {"car", "bike"} and price and 0 < price <= 1000000):
        return admin_page("Check the vehicle name, type and daily price.", vehicle_id, 400)
    upload = request.files.get("photo")
    replacement = None
    existing = None
    if vehicle_id is not None:
        existing = db().execute("SELECT img FROM vehicles WHERE id=%s", (vehicle_id,)).fetchone()
        if existing is None:
            abort(404)
    if upload and upload.filename:
        try:
            with Image.open(upload.stream, formats=["JPEG", "PNG", "WEBP"]) as image:
                if image.width * image.height > 25000000:
                    raise ValueError("Image too large")
                image = ImageOps.exif_transpose(image).convert("RGB")
                image.thumbnail((1600, 1600))
                output = io.BytesIO()
                image.save(output, format="WEBP", quality=85)
                replacement = output.getvalue()
        except (UnidentifiedImageError, OSError, ValueError, Image.DecompressionBombError):
            return admin_page("Upload a valid JPEG, PNG or WebP image under 25 megapixels.", vehicle_id, 400)
    if existing is None and replacement is None:
        return admin_page("Choose an image for the new vehicle.", status=400)
    connection = db()
    with connection.transaction():
        if vehicle_id is None:
            connection.execute(
                "INSERT INTO vehicles (name,type,price,meta,img,photo) VALUES (%s,%s,%s,%s,%s,%s)",
                (name, category, price, meta, "", replacement),
            )
        elif not connection.execute(
            "UPDATE vehicles SET name=%s,type=%s,price=%s,meta=%s,photo=COALESCE(%s,photo) WHERE id=%s",
            (name, category, price, meta, replacement, vehicle_id),
        ).rowcount:
            abort(404)
    return redirect(url_for("admin"))


@app.post("/admin/vehicles/<int:vehicle_id>/delete")
@admin_only
def delete_vehicle(vehicle_id):
    require_token(request.form.get("token"))
    connection = db()
    with connection.transaction():
        if not connection.execute("DELETE FROM vehicles WHERE id=%s", (vehicle_id,)).rowcount:
            abort(404)
    return redirect(url_for("admin"))


@app.post("/admin/bookings/<reference>")
@admin_only
def update_booking(reference):
    require_token(request.form.get("token"))
    status = request.form.get("status")
    if status not in {"Pending", "Confirmed", "Declined", "Completed"}:
        abort(400)
    connection = db()
    with connection.transaction():
        if not connection.execute("UPDATE bookings SET status=%s WHERE reference=%s", (status, reference)).rowcount:
            abort(404)
    return redirect(url_for("admin") + "#bookings")


@app.after_request
def headers(response):
    response.headers["X-Content-Type-Options"] = "nosniff"
    response.headers["X-Frame-Options"] = "DENY"
    if request.path == "/" or request.path.startswith("/admin"):
        response.headers["Cache-Control"] = "no-store"
    return response
